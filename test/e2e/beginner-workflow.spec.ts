import { test, expect, _electron as electron } from '@playwright/test'
import fs from 'node:fs/promises'
import path from 'node:path'
import { randomUUID } from 'node:crypto'

const root = path.resolve(import.meta.dirname, '../..')
const shots = path.join(root, '.impeccable/review/beginner-workflow')

test('tutorial, unified template models, practical guidance, duplication and layout survive project reopening', async () => {
  test.setTimeout(100_000)
  const folder = path.join(root, 'test-results', `beginner-${randomUUID()}`)
  await fs.mkdir(folder, { recursive: true })
  await fs.mkdir(shots, { recursive: true })
  const app = await electron.launch({ args: ['.', '--no-sandbox', `--user-data-dir=${folder}/profile`], cwd: root })
  const errors: string[] = []
  try {
    const page = await app.firstWindow()
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width: 1920, height: 1080 })
    await page.getByRole('button', { name: '项目与模板', exact: true }).click()
    await page.getByRole('heading', { name: '我的项目', exact: true }).waitFor()
    await page.getByRole('button', { name: '新手教程', exact: true }).click()
    const tutorial = page.getByRole('dialog', { name: '新手教程', exact: true })
    await expect(tutorial.getByRole('heading', { name: '先做一张原创角色图' })).toBeVisible()
    await tutorial.getByRole('button', { name: '2. 模型配置', exact: true }).click()
    await expect(tutorial).toContainText('读取可用模型')
    await page.screenshot({ path: path.join(shots, 'tutorial-desktop.png') })
    await page.setViewportSize({ width: 1024, height: 768 })
    expect(await tutorial.evaluate(e => e.scrollWidth - e.clientWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: path.join(shots, 'tutorial-1024.png') })
    for (let i = 3; i <= 7; i++) {
      await tutorial.getByRole('button', { name: new RegExp(`^${i}\\.`) }).click()
      await expect(tutorial.locator('h3')).toBeVisible()
    }
    await page.keyboard.press('Escape')
    await expect(tutorial).toHaveCount(0)

    const workspace = path.join(folder, 'workspace')
    await fs.mkdir(workspace)
    await app.evaluate(({ dialog }, workspace) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [workspace] }) }, workspace)
    await page.getByRole('button', { name: '新建项目', exact: true }).first().click()
    const create = page.getByRole('dialog', { name: '新建项目', exact: true })
    await create.getByLabel('项目名称', { exact: true }).fill('新手实操测试')
    await create.getByLabel('起步模板', { exact: true }).selectOption('product-video')
    await create.getByLabel('模板图片模型（统一应用）', { exact: true }).selectOption('google-gemini-3-pro-image')
    await create.getByLabel('模板视频模型（统一应用）', { exact: true }).selectOption('seedance-2.0')
    await create.getByLabel('模板视频模型（统一应用）').scrollIntoViewIfNeeded()
    await page.screenshot({ path: path.join(shots, 'models-1024.png') })
    await create.getByRole('button', { name: /选择项目目录/ }).click()
    await create.getByRole('button', { name: '创建项目', exact: true }).click()
    await page.getByTitle('添加图片节点').waitFor()
    const initial = await page.evaluate(workspace => window.electronAPI.loadCanvasSnapshot(workspace), workspace) as any
    expect(initial.nodes).toHaveLength(6)
    expect(initial.nodes.every((n: any) => n.data.workflowId === (n.data.kind === 'image' ? 'google-gemini-3-pro-image' : 'seedance-2.0'))).toBe(true)
    await page.getByRole('button', { name: '实操指引', exact: true }).click()
    const guide = page.getByRole('complementary', { name: '实操指引', exact: true })
    await expect(guide).toContainText('先完成一张图片')
    await expect(guide).toContainText('人工检查')
    await page.screenshot({ path: path.join(shots, 'canvas-1024.png') })
    await page.setViewportSize({ width: 1920, height: 1080 })
    await page.screenshot({ path: path.join(shots, 'canvas-desktop.png') })
    await page.getByRole('button', { name: '收起指引', exact: true }).click()
    await page.getByRole('button', { name: '适应画布', exact: true }).click()
    const first = page.locator(`.react-flow__node[data-id="${initial.nodes[0].id}"]`)
    await first.click()
    await page.getByRole('button', { name: '画布教程', exact: true }).click()
    await page.keyboard.press('Control+d')
    await page.keyboard.press('Delete')
    await page.keyboard.press('Escape')
    await expect(page.getByRole('button', { name: '画布教程', exact: true })).toBeFocused()
    await page.getByRole('button', { name: '复制选择', exact: true }).click()
    await page.keyboard.press('Control+d')
    await page.keyboard.press('Control+z')
    await page.getByRole('button', { name: '返回', exact: true }).click()
    let saved = await page.evaluate(workspace => window.electronAPI.loadCanvasSnapshot(workspace), workspace) as any
    expect(saved.nodes).toHaveLength(7)
    const copy = saved.nodes.find((n: any) => !initial.nodes.some((old: any) => old.id === n.id))
    expect(copy.data.prompt).toBe(initial.nodes[0].data.prompt)
    expect(copy.data.sourcePath).toBeUndefined()
    await page.getByRole('button', { name: '打开项目 新手实操测试', exact: true }).click()
    await page.getByTitle('添加图片节点').waitFor()
    await page.getByRole('button', { name: '整理布局', exact: true }).click()
    await page.getByRole('button', { name: '撤销画布修改', exact: true }).click()
    await page.getByRole('button', { name: '返回', exact: true }).click()
    const undone = await page.evaluate(workspace => window.electronAPI.loadCanvasSnapshot(workspace), workspace) as any
    expect(undone.nodes.map((n: any) => n.position)).toEqual(saved.nodes.map((n: any) => n.position))
    await page.getByRole('button', { name: '打开项目 新手实操测试', exact: true }).click()
    await page.getByTitle('添加图片节点').waitFor()
    await page.getByRole('button', { name: '整理布局', exact: true }).click()
    await page.getByRole('button', { name: '返回', exact: true }).click()
    saved = await page.evaluate(workspace => window.electronAPI.loadCanvasSnapshot(workspace), workspace) as any
    expect(new Set(saved.nodes.map((n: any) => `${n.position.x}:${n.position.y}`)).size).toBe(7)
    expect(saved.nodes.map((n: any) => n.data)).toEqual(undone.nodes.map((n: any) => n.data))
    await page.getByRole('button', { name: '打开项目 新手实操测试', exact: true }).click()
    await page.getByTitle('添加3D 导演台节点', { exact: true }).click()
    await page.getByRole('button', { name: '适应画布', exact: true }).click()
    await page.getByRole('button', { name: '打开导演台', exact: true }).click()
    const directorHelp = page.getByRole('button', { name: '导演台教程', exact: true })
    await directorHelp.click()
    const directorTutorial = page.getByRole('dialog', { name: '导演台教程', exact: true })
    await expect(directorTutorial.getByRole('heading', { name: '先完成一个简单镜头' })).toBeVisible()
    await page.keyboard.press('Control+d')
    await page.keyboard.press('Control+z')
    await page.keyboard.press('Escape')
    await expect(directorHelp).toBeFocused()
    await page.getByRole('button', { name: '保存并关闭', exact: true }).click()
    await page.getByRole('button', { name: '返回', exact: true }).click()
    const withDirector = await page.evaluate(workspace => window.electronAPI.loadCanvasSnapshot(workspace), workspace) as any
    expect(withDirector.nodes).toHaveLength(8)
    const director = withDirector.nodes.find((n: any) => n.data.kind === 'director')
    expect(director.data.directorProject.elements).toHaveLength(0)
    await expect(fs.access(path.join(workspace, '.aigc-line/generation-tasks'))).rejects.toThrow()
    expect(errors).toEqual([])
  } finally { await app.evaluate(({ app }) => app.exit(0)).catch(() => undefined) }
})
